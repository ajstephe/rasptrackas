  await p.addInitScript(`(${seed.toString()})('light')`);
  await p.goto('http://localhost:4332/'); await p.waitForTimeout(1800);
  const nav = i => p.locator('.app-nav button').nth(i).click().then(()=>p.waitForTimeout(900));
